function currentLang() {
  const l = localStorage.getItem(LANG_KEY);
  return DICT[l] ? l : "en";
}

function t(key, vars) {
  const l = currentLang();
  let s = (DICT[l] && DICT[l][key]) ?? DICT.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, vars[k]);
  return s;
}

function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.innerHTML = t(key); // a few strings intentionally carry <b>/<br> (see dict)
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  // Phase 7: same pattern for title/aria-label attributes, used by the
  // vehicle-selector limitation note and icon-only button accessibility
  // labels (bug #19) so those stay translated too.
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  document.documentElement.lang = currentLang();
}

function setLang(lang) {
  if (!DICT[lang]) return;
  localStorage.setItem(LANG_KEY, lang);
  applyI18n(document);
  document.dispatchEvent(new CustomEvent("nerai-lang-changed", { detail: { lang } }));
}

window.I18N = { t, applyI18n, setLang, currentLang, CATEGORIES: ["road_damage","landslide","flood","bridge_damage","blockage","traffic","other"] };

document.addEventListener("DOMContentLoaded", () => applyI18n(document));
